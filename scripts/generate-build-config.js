// Bakes the server URL into the build. The TOKITOKI_BASE_URL environment
// variable at compile time selects the server (for staging/test packages);
// unset builds talk to production. Runs before every tsc invocation.
const fs = require('fs');
const path = require('path');

const url = (process.env.TOKITOKI_BASE_URL || 'https://tokitoki.dev').trim();

let parsed;
try {
  parsed = new URL(url);
} catch {
  throw new Error(`TOKITOKI_BASE_URL is not a valid URL: ${url}`);
}
if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
  throw new Error(`TOKITOKI_BASE_URL must be http(s): ${url}`);
}

const target = path.join(__dirname, '..', 'src', 'serverUrl.ts');
fs.writeFileSync(
  target,
  `// Generated by scripts/generate-server-url.js at build time. Do not edit.\n` +
  `export const TOKITOKI_BASE_URL = '${url}';\n`,
);
console.log(`Server URL baked into build: ${url}`);
