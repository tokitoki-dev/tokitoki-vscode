// Bakes the build parameters into the extension. Two environment variables at
// compile time select them; unset, a build is a production build:
//
//   TOKITOKI_BASE_URL   the server the dashboard links open (https://tokitoki.dev)
//   TOKITOKI_DATA_DIR   the CLI's directory under $HOME, where the shared
//                       binary, the API key and the event queue live (.tokitoki)
//
// The two are one decision, not two: a CLI stamped with a data directory also
// carries the server it reports to (tokitoki-cli/Makefile), so an extension
// that looks for the shared CLI under .tokitoki-dev is by construction one
// that talks to the dev server. Runs before every tsc invocation.
const fs = require('fs');
const path = require('path');

const url = (process.env.TOKITOKI_BASE_URL || 'https://tokitoki.dev').trim();
const dataDir = (process.env.TOKITOKI_DATA_DIR || '.tokitoki').trim();

let parsed;
try {
  parsed = new URL(url);
} catch {
  throw new Error(`TOKITOKI_BASE_URL is not a valid URL: ${url}`);
}
if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
  throw new Error(`TOKITOKI_BASE_URL must be http(s): ${url}`);
}

// The same rule the CLI applies to its own stamp (internal/config): a single
// directory name, never a path.
if (!dataDir || dataDir === '.' || dataDir === '..' || /[\\/]/.test(dataDir)) {
  throw new Error(`TOKITOKI_DATA_DIR must be a single directory name, not a path: ${dataDir}`);
}

const target = path.join(__dirname, '..', 'src', 'buildConfig.ts');
fs.writeFileSync(
  target,
  `// Generated by scripts/generate-build-config.js at build time. Do not edit.\n` +
  `export const TOKITOKI_BASE_URL = '${url}';\n` +
  `export const TOKITOKI_DATA_DIR = '${dataDir}';\n`,
);
console.log(`Baked into build: server ${url}, data dir ~/${dataDir}`);
